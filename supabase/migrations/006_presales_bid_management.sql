create or replace function public.initialize_presales_stages() returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.presales_stage_history(project_id,stage_id,status,assigned_to,planned_start,due_date,updated_by,updated_by_email)
  select new.id,t.id,case when t.sequence_no=1 then 'In Progress' else 'Not Started' end,t.accountable_group,
    case when t.sequence_no=1 then new.start_date else null end,
    case when t.sequence_no=1 and t.target_days is not null then new.start_date+t.target_days else null end,
    auth.uid(),coalesce(auth.jwt()->>'email','')
  from public.presales_stage_templates t where t.active=true;
  update public.presales_projects set current_stage_id=(select id from public.presales_stage_templates where sequence_no=1) where id=new.id;
  return new;
end;$$;
drop trigger if exists initialize_presales_project on public.presales_projects;
create trigger initialize_presales_project after insert on public.presales_projects for each row execute function public.initialize_presales_stages();

create or replace function public.set_presales_project_audit() returns trigger language plpgsql security definer set search_path=public as $$
begin
  new.updated_at=now(); new.updated_by=auth.uid();
  insert into public.audit_logs(user_id,user_email,action,record_type,record_code,changes)
  values(auth.uid(),coalesce(auth.jwt()->>'email',''),case when tg_op='INSERT' then 'Created' else 'Updated' end,'presales_project',new.bid_reference,to_jsonb(new));
  return new;
end;$$;
drop trigger if exists audit_presales_project on public.presales_projects;
create trigger audit_presales_project before insert or update on public.presales_projects for each row execute function public.set_presales_project_audit();

create or replace function public.update_presales_stage(
  p_history_id bigint,p_status text,p_assigned_to text,p_planned_start date,p_due_date date,
  p_actual_start date,p_completed_date date,p_documents_complete boolean,p_notes text
) returns public.presales_stage_history language plpgsql security definer set search_path=public as $$
declare v_history public.presales_stage_history; v_project public.presales_projects; v_stage public.presales_stage_templates; v_next bigint;
begin
  if public.current_user_role() not in ('Admin','Editor') then raise exception 'You have view-only access.'; end if;
  select * into v_history from public.presales_stage_history where id=p_history_id for update;
  if not found then raise exception 'Stage record not found.'; end if;
  select * into v_stage from public.presales_stage_templates where id=v_history.stage_id;
  update public.presales_stage_history set status=p_status,assigned_to=coalesce(p_assigned_to,''),planned_start=p_planned_start,due_date=p_due_date,
    actual_start=p_actual_start,completed_date=p_completed_date,documents_complete=coalesce(p_documents_complete,false),notes=coalesce(p_notes,''),
    updated_by=auth.uid(),updated_by_email=coalesce(auth.jwt()->>'email',''),updated_at=now() where id=p_history_id returning * into v_history;
  if p_status='Completed' then
    select h.id into v_next from public.presales_stage_history h join public.presales_stage_templates t on t.id=h.stage_id
      where h.project_id=v_history.project_id and t.sequence_no>v_stage.sequence_no and h.status='Not Started' order by t.sequence_no limit 1;
    if v_next is not null then
      update public.presales_stage_history h set status='In Progress',actual_start=coalesce(h.actual_start,current_date),planned_start=coalesce(h.planned_start,current_date),
        due_date=coalesce(h.due_date,current_date+t.target_days),updated_by=auth.uid(),updated_by_email=coalesce(auth.jwt()->>'email',''),updated_at=now()
      from public.presales_stage_templates t where h.id=v_next and t.id=h.stage_id;
      update public.presales_projects set current_stage_id=(select stage_id from public.presales_stage_history where id=v_next) where id=v_history.project_id;
    end if;
  else
    update public.presales_projects set current_stage_id=v_history.stage_id where id=v_history.project_id;
  end if;
  insert into public.audit_logs(user_id,user_email,action,record_type,record_code,changes)
  values(auth.uid(),coalesce(auth.jwt()->>'email',''),'Stage updated','presales_stage',v_stage.stage_name,to_jsonb(v_history));
  return v_history;
end;$$;

