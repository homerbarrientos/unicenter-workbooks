create table if not exists public.presales_stage_templates (
  id bigint generated by default as identity primary key,
  sequence_no integer not null unique,
  stage_name text not null unique,
  accountable_group text not null,
  control_type text not null default 'Internal' check (control_type in ('Internal','Client','Shared')),
  target_days integer,
  timing_anchor text not null default '',
  required_documents text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.presales_projects (
  id bigint generated by default as identity primary key,
  bid_reference text not null unique,
  customer_name text not null,
  project_name text not null,
  opportunity_value numeric(15,2) not null default 0 check (opportunity_value >= 0),
  owner text not null default '',
  priority text not null default 'Medium' check (priority in ('Critical','High','Medium','Low')),
  bid_status text not null default 'Active' check (bid_status in ('Active','On Hold','Won','Lost','Cancelled')),
  start_date date not null default current_date,
  expected_bid_date date,
  current_stage_id bigint references public.presales_stage_templates(id),
  remarks text not null default '',
  created_by uuid references auth.users(id),
  updated_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.presales_stage_history (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.presales_projects(id) on delete cascade,
  stage_id bigint not null references public.presales_stage_templates(id),
  status text not null default 'Not Started' check (status in ('Not Started','In Progress','Completed','Blocked','Skipped')),
  assigned_to text not null default '',
  planned_start date,
  due_date date,
  actual_start date,
  completed_date date,
  documents_complete boolean not null default false,
  notes text not null default '',
  updated_by uuid references auth.users(id),
  updated_by_email text not null default '',
  updated_at timestamptz not null default now(),
  unique(project_id,stage_id)
);

create index if not exists idx_presales_projects_status on public.presales_projects(bid_status);
create index if not exists idx_presales_stage_history_project on public.presales_stage_history(project_id);
create index if not exists idx_presales_stage_history_due on public.presales_stage_history(due_date);

